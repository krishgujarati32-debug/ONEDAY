import type { Topic } from "@/lib/types";
import type { DepthRow } from "./course-v5-types";

type Refinement = readonly [
  id: string,
  concepts: string,
  skill: string,
  boundary: string,
  check: string,
  practice?: string,
  extraMinutes?: readonly [number, number],
];

export function refineExistingTopics(
  topics: readonly Topic[],
  refinements: readonly Refinement[],
): DepthRow[] {
  return refinements.map(
    (
      [id, concepts, skill, boundary, check, practice, extraMinutes],
      position,
    ) => {
      const topic = topics[position];
      if (topic?.id !== id)
        throw new Error("V5 refinement is out of order for " + id);
      const practical = topic.subtopics.find((lesson) => lesson.workedExample);
      if (!practical)
        throw new Error("V5 refinement requires a worked lesson for " + id);
      return [
        id,
        [id],
        concepts.split(" | "),
        skill,
        boundary,
        practice ?? practical.exercise,
        check,
        extraMinutes ?? [25, 60],
      ];
    },
  );
}

